import { setTimeout as sleep } from 'node:timers/promises';
import {
  CodingAgentError,
  type CodingAgent,
  type CodingAgentInfo,
  type CodingAgentRequest,
  type CodingAgentResult,
} from './coding-agent.js';

export type FakeResponder = (request: CodingAgentRequest, call: number) => string | Promise<string>;

/**
 * A deterministic stand-in for a real coding agent: for tests, and for trying workflows
 * offline. It never contacts any service and reads nothing; its answer comes from `respond`.
 */
export class FakeCodingAgent implements CodingAgent {
  readonly id = 'fake';
  readonly displayName = 'Fake agent (offline, no AI)';
  readonly #respond: FakeResponder;
  readonly #delayMs: number;
  calls = 0;
  readonly requests: CodingAgentRequest[] = [];

  constructor(options: { respond?: FakeResponder; delayMs?: number } = {}) {
    this.#respond = options.respond ?? defaultFakeResponse;
    this.#delayMs = options.delayMs ?? 0;
  }

  probe(): Promise<CodingAgentInfo> {
    return Promise.resolve({
      id: this.id,
      displayName: this.displayName,
      available: true,
      version: null,
      reason: null,
      dataNotice: 'Offline stand-in: nothing leaves this machine, and nothing is analysed.',
    });
  }

  async execute(request: CodingAgentRequest): Promise<CodingAgentResult> {
    this.calls += 1;
    this.requests.push(request);
    const started = Date.now();
    if (this.#delayMs > 0) {
      try {
        await sleep(this.#delayMs, undefined, { signal: request.signal });
      } catch {
        throw new CodingAgentError('AGENT_CANCELLED', 'The fake agent run was stopped.', false);
      }
    }
    const text = await this.#respond(request, this.calls);
    return { text, costUsd: 0, turns: 1, durationMs: Date.now() - started, sessionId: null };
  }
}

/**
 * Builds a placeholder spec that passes the Generate Spec checks, from the file list in the
 * prompt. It says plainly that no analysis took place.
 */
export function defaultFakeResponse(request: CodingAgentRequest): string {
  const files = [...request.prompt.matchAll(/^- `([^`]+)`/gm)].map((m) => m[1]).slice(0, 10);
  const title = /^Title: (.+)$/m.exec(request.prompt)?.[1] ?? 'Specification';
  const cited = files.length === 0 ? '(none listed)' : files.map((f) => `\`${f}\``).join(', ');
  return [
    `# ${title}`,
    '',
    '> Generated by the offline fake agent. No AI analysis took place; every statement below is a placeholder.',
    '',
    '## Screen overview',
    `Placeholder. Files in scope: ${cited}.`,
    '',
    '## Business purpose',
    'Not determined: the fake agent does not read code.',
    '',
    '## UI components',
    'Not determined.',
    '',
    '## User interactions',
    'Not determined.',
    '',
    '## Validation rules',
    'Not determined.',
    '',
    '## Data dependencies',
    'Not determined.',
    '',
    '## API interactions',
    'Not determined.',
    '',
    '## Loading, empty and error states',
    'Not determined.',
    '',
    '## Assumptions and unresolved questions',
    '- Assumption: this document is a placeholder produced without a coding agent.',
    '',
  ].join('\n');
}
