import { z } from 'zod';

/**
 * Lifecycle of one execution. It says where the execution is in its life, not which business
 * step it is on; that is the workflow's own machine state (`currentState`).
 */
export const EXECUTION_STATUSES = [
  'PENDING',
  'RUNNING',
  'WAITING_FOR_APPROVAL',
  /** Stopped in a way the platform cannot safely continue alone. Needs a person to decide. */
  'INTERRUPTED',
  'FAILED',
  'CANCELLED',
  'COMPLETED',
] as const;

export const executionStatusSchema = z.enum(EXECUTION_STATUSES);
export type ExecutionStatus = z.infer<typeof executionStatusSchema>;

export const TERMINAL_EXECUTION_STATUSES = [
  'COMPLETED',
  'FAILED',
  'CANCELLED',
] as const satisfies readonly ExecutionStatus[];

/** One attempt at running one step. */
export const STEP_RUN_STATUSES = ['RUNNING', 'SUCCEEDED', 'FAILED', 'INTERRUPTED'] as const;

export const stepRunStatusSchema = z.enum(STEP_RUN_STATUSES);
export type StepRunStatus = z.infer<typeof stepRunStatusSchema>;

export const EXECUTION_EVENT_TYPES = [
  'EXECUTION_CREATED',
  'STATUS_CHANGED',
  'STEP_STARTED',
  'STEP_SUCCEEDED',
  'STEP_FAILED',
  'STEP_INTERRUPTED',
  'STATE_CHANGED',
  'CANCEL_REQUESTED',
] as const;

export const executionEventTypeSchema = z.enum(EXECUTION_EVENT_TYPES);
export type ExecutionEventType = z.infer<typeof executionEventTypeSchema>;

/** Execution ids are UUIDs generated by the engine. */
export const executionIdSchema = z.uuid();
export const workflowIdSchema = z
  .string()
  .regex(/^[a-z][a-z0-9]*(?:-[a-z0-9]+)*$/)
  .max(64);

const timestamp = z.iso.datetime();

export const errorInfoSchema = z.object({ code: z.string(), message: z.string() });

export const workflowStateSchema = z.object({
  name: z.string(),
  kind: z.enum(['step', 'final']),
  title: z.string(),
  finalStatus: executionStatusSchema.nullable(),
});

export type WorkflowStateDto = z.infer<typeof workflowStateSchema>;

export const executionSummarySchema = z.object({
  id: z.string(),
  workflowId: z.string(),
  workflowVersion: z.string(),
  /** Falls back to the id when the workflow is no longer registered. */
  workflowName: z.string(),
  status: executionStatusSchema,
  /** The workflow machine's state; separate from `status`. */
  currentState: z.string(),
  currentStateTitle: z.string(),
  error: errorInfoSchema.nullable(),
  /** A cancel was requested and the running step has not stopped yet. */
  cancelRequested: z.boolean(),
  createdAt: timestamp,
  startedAt: timestamp.nullable(),
  updatedAt: timestamp,
  completedAt: timestamp.nullable(),
});

export type ExecutionSummary = z.infer<typeof executionSummarySchema>;

export const stepRunSchema = z.object({
  id: z.string(),
  stepId: z.string(),
  title: z.string(),
  status: stepRunStatusSchema,
  attempt: z.number().int(),
  error: errorInfoSchema.nullable(),
  startedAt: timestamp,
  completedAt: timestamp.nullable(),
  durationMs: z.number().int().nullable(),
});

export type StepRun = z.infer<typeof stepRunSchema>;

export const executionDetailSchema = executionSummarySchema.extend({
  input: z.unknown(),
  output: z.unknown(),
  /** All states of the workflow, in definition order, for progress display. */
  states: z.array(workflowStateSchema),
  steps: z.array(stepRunSchema),
});

export type ExecutionDetail = z.infer<typeof executionDetailSchema>;

export const executionEventSchema = z.object({
  id: z.number().int(),
  type: executionEventTypeSchema,
  stateBefore: z.string().nullable(),
  stateAfter: z.string().nullable(),
  payload: z.unknown(),
  createdAt: timestamp,
});

export type ExecutionEvent = z.infer<typeof executionEventSchema>;

// Requests and responses

export const executionIdParamsSchema = z.object({ executionId: executionIdSchema });

export const startExecutionRequestSchema = z.object({
  workflowId: workflowIdSchema,
  /** Validated by the workflow's own input schema. */
  input: z.unknown(),
});

export type StartExecutionRequest = z.infer<typeof startExecutionRequestSchema>;

export const executionResponseSchema = z.object({ execution: executionDetailSchema });

export const listExecutionsQuerySchema = z.object({
  workflowId: workflowIdSchema.optional(),
  status: executionStatusSchema.optional(),
  limit: z.coerce.number().int().min(1).max(200).default(50),
  offset: z.coerce.number().int().min(0).default(0),
});

/** What a client sends; the schema above coerces and defaults it on the server. */
export interface ListExecutionsQuery {
  workflowId?: string | undefined;
  status?: ExecutionStatus | undefined;
  limit?: number | undefined;
  offset?: number | undefined;
}

export const listExecutionsResponseSchema = z.object({
  executions: z.array(executionSummarySchema),
  /** Matching executions in total, for paging. */
  total: z.number().int(),
});

export const listEventsQuerySchema = z.object({
  /** Return events with an id greater than this. Poll with the last id received. */
  after: z.coerce.number().int().min(0).default(0),
  limit: z.coerce.number().int().min(1).max(500).default(200),
});

export const listEventsResponseSchema = z.object({ events: z.array(executionEventSchema) });

export const cancelExecutionResponseSchema = z.object({
  execution: executionDetailSchema,
  /** `requested`: a step is still running and was asked to stop; poll for the final status. */
  outcome: z.enum(['cancelled', 'requested']),
});

export const executionStatsResponseSchema = z.object({
  total: z.number().int(),
  byStatus: z.record(executionStatusSchema, z.number().int()),
  /** Most recently finished executions, newest first. */
  recentlyFinished: z.array(executionSummarySchema),
});

export type ExecutionStats = z.infer<typeof executionStatsResponseSchema>;
